"""Persistence boundary for canonical teacher intervention commands.

The caller owns the PostgreSQL connection and transaction.

Identity is generated by the application layer. This module validates and
persists the supplied intervention key; it never creates replacement UUIDs,
timestamps, student identities, or analysis identities.
"""

from __future__ import annotations

import json
from collections.abc import Mapping
from datetime import datetime, timezone
from typing import Any
from uuid import UUID

from psycopg.types.json import Jsonb


_ALLOWED_FIELDS = frozenset(
    {
        "interventionKey",
        "studentKey",
        "actionType",
        "analysisKey",
        "createdAt",
        "provenance",
    }
)

_REQUIRED_FIELDS = frozenset(
    {
        "interventionKey",
        "studentKey",
        "actionType",
        "createdAt",
        "provenance",
    }
)


def _require_non_empty_string(value: Any, field: str) -> str:
    if not isinstance(value, str):
        raise ValueError(f"{field} must be a string")

    normalized = value.strip()

    if not normalized:
        raise ValueError(f"{field} must not be blank")

    return normalized


def _canonical_uuid(value: Any) -> str:
    if not isinstance(value, (str, UUID)):
        raise ValueError("interventionKey must be a UUID")

    try:
        return str(UUID(str(value)))
    except (TypeError, ValueError, AttributeError) as exc:
        raise ValueError("interventionKey must be a valid UUID") from exc


def _canonical_created_at(value: Any) -> datetime:
    if isinstance(value, datetime):
        parsed = value
    elif isinstance(value, str):
        candidate = value.strip()

        if not candidate:
            raise ValueError("createdAt must not be blank")

        if candidate.endswith("Z"):
            candidate = candidate[:-1] + "+00:00"

        try:
            parsed = datetime.fromisoformat(candidate)
        except ValueError as exc:
            raise ValueError(
                "createdAt must be an ISO-8601 timestamp"
            ) from exc
    else:
        raise ValueError(
            "createdAt must be a datetime or ISO-8601 string"
        )

    if parsed.tzinfo is None or parsed.utcoffset() is None:
        raise ValueError("createdAt must include a timezone")

    return parsed.astimezone(timezone.utc)


def _canonical_provenance(value: Any) -> dict[str, Any]:
    if not isinstance(value, Mapping):
        raise ValueError("provenance must be an object")

    try:
        encoded = json.dumps(
            dict(value),
            sort_keys=True,
            separators=(",", ":"),
            ensure_ascii=False,
        )
        canonical = json.loads(encoded)
    except (TypeError, ValueError) as exc:
        raise ValueError(
            "provenance must contain JSON-compatible values"
        ) from exc

    if not isinstance(canonical, dict):
        raise ValueError("provenance must be an object")

    return canonical


def canonicalize_teacher_intervention(
    intervention: Mapping[str, Any],
) -> dict[str, Any]:
    """Validate and normalize a canonical intervention command.

    The contract is fail-closed: unknown fields are rejected rather than
    silently persisted.
    """

    if not isinstance(intervention, Mapping):
        raise ValueError("intervention must be an object")

    supplied = frozenset(intervention.keys())

    unknown = supplied - _ALLOWED_FIELDS

    if unknown:
        raise ValueError(
            "unsupported intervention fields: "
            + ", ".join(sorted(str(item) for item in unknown))
        )

    missing = _REQUIRED_FIELDS - supplied

    if missing:
        raise ValueError(
            "missing intervention fields: "
            + ", ".join(sorted(missing))
        )

    analysis_key = intervention.get("analysisKey")

    if analysis_key is not None:
        analysis_key = _require_non_empty_string(
            analysis_key,
            "analysisKey",
        )

    return {
        "interventionKey": _canonical_uuid(
            intervention["interventionKey"]
        ),
        "studentKey": _require_non_empty_string(
            intervention["studentKey"],
            "studentKey",
        ),
        "actionType": _require_non_empty_string(
            intervention["actionType"],
            "actionType",
        ),
        "analysisKey": analysis_key,
        "createdAt": _canonical_created_at(
            intervention["createdAt"]
        ),
        "provenance": _canonical_provenance(
            intervention["provenance"]
        ),
    }


def _row_to_intervention(row: tuple[Any, ...]) -> dict[str, Any]:
    (
        intervention_key,
        student_key,
        action_type,
        analysis_key,
        created_at,
        provenance,
    ) = row

    return {
        "interventionKey": str(intervention_key),
        "studentKey": student_key,
        "actionType": action_type,
        "analysisKey": analysis_key,
        "createdAt": created_at.astimezone(timezone.utc),
        "provenance": provenance,
    }


def load_teacher_intervention(
    cursor: Any,
    intervention_key: str | UUID,
) -> dict[str, Any] | None:
    """Load one canonical intervention by application-owned identity."""

    canonical_key = _canonical_uuid(intervention_key)

    cursor.execute(
        """
        SELECT
            intervention_key,
            student_key,
            action_type,
            analysis_key,
            created_at,
            provenance
        FROM teacher_interventions
        WHERE intervention_key = %s
        """,
        (canonical_key,),
    )

    row = cursor.fetchone()

    if row is None:
        return None

    return _row_to_intervention(row)


def persist_teacher_intervention(
    cursor: Any,
    intervention: Mapping[str, Any],
) -> tuple[dict[str, Any], bool]:
    """Persist a canonical intervention using append-only semantics.

    Returns ``(payload, created)``.

    Replaying the exact same command is idempotent. Reusing an existing
    intervention key for a different canonical payload fails closed.
    """

    canonical = canonicalize_teacher_intervention(
        intervention
    )

    cursor.execute(
        """
        INSERT INTO teacher_interventions (
            intervention_key,
            student_key,
            action_type,
            analysis_key,
            created_at,
            provenance
        )
        VALUES (
            %s,
            %s,
            %s,
            %s,
            %s,
            %s
        )
        ON CONFLICT (intervention_key)
        DO NOTHING
        RETURNING
            intervention_key,
            student_key,
            action_type,
            analysis_key,
            created_at,
            provenance
        """,
        (
            canonical["interventionKey"],
            canonical["studentKey"],
            canonical["actionType"],
            canonical["analysisKey"],
            canonical["createdAt"],
            Jsonb(canonical["provenance"]),
        ),
    )

    inserted = cursor.fetchone()

    if inserted is not None:
        return _row_to_intervention(inserted), True

    existing = load_teacher_intervention(
        cursor,
        canonical["interventionKey"],
    )

    if existing is None:
        raise RuntimeError(
            "intervention conflict occurred but existing row "
            "could not be loaded"
        )

    if existing != canonical:
        raise ValueError(
            "interventionKey already exists with a different "
            "canonical payload"
        )

    return existing, False


__all__ = [
    "canonicalize_teacher_intervention",
    "load_teacher_intervention",
    "persist_teacher_intervention",
]