"""Verify parity between operational PostgreSQL metrics and dbt analytical marts."""

from __future__ import annotations

import json
import os
import sys
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path
from typing import Any

import psycopg
from psycopg import sql
from psycopg.rows import dict_row


DEFAULT_MANIFEST_PATH = (
    Path(__file__).resolve().parents[1] / "target" / "manifest.json"
)


def get_database_url() -> str:
    """Return the configured PostgreSQL URL without credential fallbacks."""
    database_url = os.environ.get("LOTUSLEARN_DATABASE_URL")
    if database_url:
        return database_url

    test_database_url = os.environ.get("LOTUSLEARN_TEST_DATABASE_URL")
    if test_database_url:
        return test_database_url

    raise RuntimeError(
        "Database URL is required. Set LOTUSLEARN_DATABASE_URL "
        "or LOTUSLEARN_TEST_DATABASE_URL."
    )


def load_manifest(manifest_path: Path) -> dict[str, Any]:
    """Load the dbt manifest generated by the current dbt build."""
    if not manifest_path.exists():
        raise FileNotFoundError(
            f"dbt manifest not found at {manifest_path}. "
            "Run dbt build before parity verification."
        )

    with manifest_path.open("r", encoding="utf-8") as manifest_file:
        manifest = json.load(manifest_file)

    if not isinstance(manifest, dict):
        raise RuntimeError("dbt manifest root must be a JSON object.")

    if "nodes" not in manifest or "sources" not in manifest:
        raise RuntimeError(
            "dbt manifest is missing required nodes or sources metadata."
        )

    return manifest


def resolve_model_relation(
    manifest: dict[str, Any],
    model_name: str,
) -> sql.Composed:
    """
    Resolve a dbt model using the manifest produced by the active target.

    The verifier intentionally does not assume a physical schema such as
    analytics or analytics_analytics. dbt remains authoritative for model
    placement.
    """
    matches = [
        node
        for node in manifest["nodes"].values()
        if node.get("resource_type") == "model"
        and node.get("name") == model_name
    ]

    if len(matches) != 1:
        raise RuntimeError(
            f"Expected exactly one dbt model named {model_name!r}, "
            f"found {len(matches)}."
        )

    node = matches[0]
    schema_name = node.get("schema")
    identifier = node.get("alias") or node.get("name")

    if not schema_name or not identifier:
        raise RuntimeError(
            f"dbt model {model_name!r} has incomplete relation metadata."
        )

    return sql.SQL("{}.{}").format(
        sql.Identifier(schema_name),
        sql.Identifier(identifier),
    )


def resolve_source_relation(
    manifest: dict[str, Any],
    source_table_name: str,
) -> sql.Composed:
    """Resolve an operational source relation from dbt source metadata."""
    matches = [
        source
        for source in manifest["sources"].values()
        if (
            source.get("name") == source_table_name
            or source.get("identifier") == source_table_name
        )
    ]

    if len(matches) != 1:
        raise RuntimeError(
            f"Expected exactly one dbt source for {source_table_name!r}, "
            f"found {len(matches)}."
        )

    source = matches[0]
    schema_name = source.get("schema")
    identifier = source.get("identifier") or source.get("name")

    if not schema_name or not identifier:
        raise RuntimeError(
            f"dbt source {source_table_name!r} has incomplete relation metadata."
        )

    return sql.SQL("{}.{}").format(
        sql.Identifier(schema_name),
        sql.Identifier(identifier),
    )


def resolve_operational_view(
    manifest: dict[str, Any],
    view_name: str,
) -> sql.Composed:
    """
    Resolve an operational SQL view in the same schema as analysis_runs.

    The DE-02 operational tables and metric views share the operational schema.
    This avoids assuming that schema is always public.
    """
    analysis_run_sources = [
        source
        for source in manifest["sources"].values()
        if (
            source.get("name") == "analysis_runs"
            or source.get("identifier") == "analysis_runs"
        )
    ]

    if len(analysis_run_sources) != 1:
        raise RuntimeError(
            "Unable to determine the operational schema from analysis_runs."
        )

    schema_name = analysis_run_sources[0].get("schema")
    if not schema_name:
        raise RuntimeError(
            "analysis_runs source does not define an operational schema."
        )

    return sql.SQL("{}.{}").format(
        sql.Identifier(schema_name),
        sql.Identifier(view_name),
    )


def decimal_or_none(value: Any) -> Decimal | None:
    """Normalize PostgreSQL numeric values without converting through float."""
    if value is None:
        return None
    if isinstance(value, Decimal):
        return value
    return Decimal(str(value))


def four_decimal_ratio(
    numerator: int,
    denominator: int,
) -> Decimal | None:
    """Calculate a deterministic four-decimal ratio."""
    if denominator == 0:
        return None

    return (
        Decimal(numerator) / Decimal(denominator)
    ).quantize(
        Decimal("0.0001"),
        rounding=ROUND_HALF_UP,
    )


def verify_dbt_parity(
    database_url: str,
    manifest_path: Path = DEFAULT_MANIFEST_PATH,
) -> None:
    """Assert parity between operational truth and dbt analytical outputs."""
    manifest = load_manifest(manifest_path)

    analysis_runs = resolve_source_relation(
        manifest,
        "analysis_runs",
    )
    analytical_events = resolve_source_relation(
        manifest,
        "analytical_events",
    )

    dim_analysis_run = resolve_model_relation(
        manifest,
        "dim_analysis_run",
    )
    fct_ingestion_attempts = resolve_model_relation(
        manifest,
        "fct_ingestion_attempts",
    )
    mart_run_quality = resolve_model_relation(
        manifest,
        "mart_run_quality",
    )
    mart_concept_prevalence = resolve_model_relation(
        manifest,
        "mart_concept_prevalence",
    )

    v_run_scoped_students = resolve_operational_view(
        manifest,
        "v_run_scoped_students",
    )
    v_educator_decisions = resolve_operational_view(
        manifest,
        "v_educator_decisions",
    )
    v_cohort_prevalence = resolve_operational_view(
        manifest,
        "v_cohort_prevalence",
    )

    print(
        "Verifying operational PostgreSQL metrics "
        "against dbt analytical models..."
    )

    with psycopg.connect(
        database_url,
        row_factory=dict_row,
    ) as conn:
        with conn.cursor() as cur:
            # 1. Analysis run parity
            cur.execute(
                sql.SQL(
                    "SELECT COUNT(*)::INTEGER AS count FROM {}"
                ).format(analysis_runs)
            )
            operational_run_count = cur.fetchone()["count"]

            cur.execute(
                sql.SQL(
                    "SELECT COUNT(*)::INTEGER AS count FROM {}"
                ).format(dim_analysis_run)
            )
            dbt_run_count = cur.fetchone()["count"]

            assert operational_run_count == dbt_run_count, (
                "Analysis run count mismatch: "
                f"operational={operational_run_count}, "
                f"dbt={dbt_run_count}"
            )

            print(
                "[PASS] Analysis run count: "
                f"{operational_run_count}"
            )

            # 2. Accepted event parity
            #
            # fct_ingestion_attempts now preserves one row per durable
            # audit attempt. event_id is intentionally not unique because
            # accepted, duplicate, conflict, and rejected attempts may
            # reference the same analytical event identity.
            cur.execute(
                sql.SQL(
                    "SELECT COUNT(*)::INTEGER AS count FROM {}"
                ).format(analytical_events)
            )
            committed_event_count = cur.fetchone()["count"]

            cur.execute(
                sql.SQL(
                    """
                    SELECT COUNT(*)::INTEGER AS count
                    FROM {}
                    WHERE outcome = 'accepted'
                    """
                ).format(fct_ingestion_attempts)
            )
            accepted_attempt_count = cur.fetchone()["count"]

            assert committed_event_count == accepted_attempt_count, (
                "Accepted event parity mismatch: "
                f"committed_events={committed_event_count}, "
                f"accepted_attempts={accepted_attempt_count}"
            )

            print(
                "[PASS] Accepted event count: "
                f"{committed_event_count}"
            )

            # 3. Student appearance parity
            cur.execute(
                sql.SQL(
                    "SELECT COUNT(*)::INTEGER AS count FROM {}"
                ).format(v_run_scoped_students)
            )
            operational_student_appearances = cur.fetchone()["count"]

            cur.execute(
                sql.SQL(
                    """
                    SELECT
                        COALESCE(
                            SUM(student_appearances_count),
                            0
                        )::INTEGER AS count
                    FROM {}
                    """
                ).format(mart_run_quality)
            )
            dbt_student_appearances = cur.fetchone()["count"]

            assert (
                operational_student_appearances
                == dbt_student_appearances
            ), (
                "Student appearance mismatch: "
                f"operational={operational_student_appearances}, "
                f"dbt={dbt_student_appearances}"
            )

            print(
                "[PASS] Run-scoped student appearances: "
                f"{operational_student_appearances}"
            )

            # 4. Educator modification parity
            cur.execute(
                sql.SQL(
                    """
                    SELECT
                        COALESCE(
                            SUM(count_accepted),
                            0
                        )::INTEGER AS total_accepted,
                        COALESCE(
                            SUM(count_edited),
                            0
                        )::INTEGER AS total_edited,
                        COALESCE(
                            SUM(count_dismissed),
                            0
                        )::INTEGER AS total_dismissed,
                        COALESCE(
                            SUM(total_reviewed),
                            0
                        )::INTEGER AS total_reviewed
                    FROM {}
                    """
                ).format(v_educator_decisions)
            )
            operational_decisions = cur.fetchone()

            operational_modification_count = (
                operational_decisions["total_edited"]
                + operational_decisions["total_dismissed"]
            )
            operational_reviewed_count = (
                operational_decisions["total_reviewed"]
            )
            operational_rate = four_decimal_ratio(
                operational_modification_count,
                operational_reviewed_count,
            )

            cur.execute(
                sql.SQL(
                    """
                    SELECT
                        COALESCE(
                            SUM(teacher_modifications_count),
                            0
                        )::INTEGER AS total_modifications,
                        COALESCE(
                            SUM(teacher_decisions_reviewed_count),
                            0
                        )::INTEGER AS total_reviewed
                    FROM {}
                    """
                ).format(mart_run_quality)
            )
            dbt_decisions = cur.fetchone()

            dbt_modification_count = (
                dbt_decisions["total_modifications"]
            )
            dbt_reviewed_count = dbt_decisions["total_reviewed"]
            dbt_rate = four_decimal_ratio(
                dbt_modification_count,
                dbt_reviewed_count,
            )

            assert (
                operational_modification_count
                == dbt_modification_count
            ), (
                "Educator modification count mismatch: "
                f"operational={operational_modification_count}, "
                f"dbt={dbt_modification_count}"
            )

            assert operational_reviewed_count == dbt_reviewed_count, (
                "Educator reviewed count mismatch: "
                f"operational={operational_reviewed_count}, "
                f"dbt={dbt_reviewed_count}"
            )

            assert operational_rate == dbt_rate, (
                "Educator modification rate mismatch: "
                f"operational={operational_rate}, "
                f"dbt={dbt_rate}"
            )

            print(
                "[PASS] Educator modification rate: "
                f"{operational_rate}"
            )

            # 5. Concept prevalence parity
            cur.execute(
                sql.SQL(
                    """
                    SELECT
                        analysis_run_id,
                        cluster_id,
                        prevalence_rate
                    FROM {}
                    ORDER BY analysis_run_id, cluster_id
                    """
                ).format(v_cohort_prevalence)
            )
            operational_prevalence = cur.fetchall()

            cur.execute(
                sql.SQL(
                    """
                    SELECT
                        analysis_run_id,
                        cluster_id,
                        prevalence_rate
                    FROM {}
                    ORDER BY analysis_run_id, cluster_id
                    """
                ).format(mart_concept_prevalence)
            )
            dbt_prevalence = cur.fetchall()

            assert len(operational_prevalence) == len(
                dbt_prevalence
            ), (
                "Concept prevalence row-count mismatch: "
                f"operational={len(operational_prevalence)}, "
                f"dbt={len(dbt_prevalence)}"
            )

            for operational_row, dbt_row in zip(
                operational_prevalence,
                dbt_prevalence,
                strict=True,
            ):
                assert (
                    operational_row["analysis_run_id"]
                    == dbt_row["analysis_run_id"]
                ), (
                    "Concept prevalence analysis_run_id mismatch: "
                    f"operational={operational_row['analysis_run_id']}, "
                    f"dbt={dbt_row['analysis_run_id']}"
                )

                assert (
                    operational_row["cluster_id"]
                    == dbt_row["cluster_id"]
                ), (
                    "Concept prevalence cluster_id mismatch: "
                    f"operational={operational_row['cluster_id']}, "
                    f"dbt={dbt_row['cluster_id']}"
                )

                operational_rate = decimal_or_none(
                    operational_row["prevalence_rate"]
                )
                dbt_rate = decimal_or_none(
                    dbt_row["prevalence_rate"]
                )

                assert operational_rate == dbt_rate, (
                    "Concept prevalence rate mismatch for "
                    f"{operational_row['cluster_id']}: "
                    f"operational={operational_rate}, "
                    f"dbt={dbt_rate}"
                )

            print(
                "[PASS] Concept prevalence rows: "
                f"{len(operational_prevalence)}"
            )

    print(
        "SUCCESS: Operational and dbt analytical parity "
        "verified with no mismatches."
    )


def main() -> int:
    """CLI entry point."""
    try:
        database_url = get_database_url()

        manifest_override = os.environ.get("DBT_MANIFEST_PATH")
        manifest_path = (
            Path(manifest_override).resolve()
            if manifest_override
            else DEFAULT_MANIFEST_PATH
        )

        verify_dbt_parity(
            database_url=database_url,
            manifest_path=manifest_path,
        )
    except Exception as exc:
        print(
            f"ERROR: Parity verification failed: {exc}",
            file=sys.stderr,
        )
        return 1

    return 0


if __name__ == "__main__":
    raise SystemExit(main())